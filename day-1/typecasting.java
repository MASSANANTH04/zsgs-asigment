public class typecasting {
    
    public static void main(String args[]){
       // typecasting 
        double num1=12.23234221233;
        float num2=(float)num1;
        long num3=(long)num1;
        int num4=(int)num1;
        short num5=(short)num1;
        byte num6=(byte)num1;

 

        System.out.println("double value is:"+num1);
        System.out.println("float valueis is:"+num2);
        System.out.println("long value is:"+num3);
        System.out.println("int value is:"+num4);
        System.out.println("short value is:"+num5);
        System.out.println("byte value is:"+num6);



    }
}
